/* ---------- Email list view ----------
   Main contact + additional contacts, one row per distinct address.
   Example: SELECT EMAIL FROM V_EMAIL_LIST
            WHERE TYPE_NAME = 'ABS Cloud' AND STATUS_NAME = 'Active';

   Customers without a type or status are left out (inner joins). */

CREATE VIEW V_EMAIL_LIST (WAVE_ID, CUSTOMER_NAME, TYPE_NAME, STATUS_NAME, EMAIL) AS
  SELECT C.WAVE_ID, C.NAME, T.NAME, S.NAME, C.EMAIL
  FROM CUSTOMER C
  JOIN CUSTOMER_TYPE   T ON T.TYPE_ID   = C.TYPE_ID
  JOIN CUSTOMER_STATUS S ON S.STATUS_ID = C.STATUS_ID
  WHERE C.IN_WAVE AND C.EMAIL <> ''
  UNION
  SELECT C.WAVE_ID, C.NAME, T.NAME, S.NAME, K.EMAIL
  FROM CONTACT K
  JOIN CUSTOMER C        ON C.WAVE_ID   = K.WAVE_ID
  JOIN CUSTOMER_TYPE   T ON T.TYPE_ID   = C.TYPE_ID
  JOIN CUSTOMER_STATUS S ON S.STATUS_ID = C.STATUS_ID
  WHERE C.IN_WAVE AND K.EMAIL <> '';


/* ---------- Customer ---------- */

CREATE TABLE CUSTOMER (
  WAVE_ID       VARCHAR(100) CHARACTER SET ASCII NOT NULL PRIMARY KEY,  -- Wave customer id (opaque base64)

  /* Wave-owned: main contact + address, overwritten by sync */
  NAME          VARCHAR(200),                        -- company name
  FIRST_NAME    VARCHAR(80),
  LAST_NAME     VARCHAR(80),
  EMAIL         VARCHAR(200),
  PHONE         VARCHAR(40),
  MOBILE        VARCHAR(40),
  WEBSITE       VARCHAR(200),
  ADDRESS1      VARCHAR(120),
  ADDRESS2      VARCHAR(120),
  CITY          VARCHAR(80),
  STATE_CODE    VARCHAR(10),                         -- e.g. US-CA
  POSTAL_CODE   VARCHAR(20),
  IN_WAVE       BOOLEAN DEFAULT TRUE NOT NULL,       -- FALSE = no longer returned by Wave
  SYNCED_AT     TIMESTAMP,

  /* Yours: never touched by sync */
  TYPE_ID       INTEGER REFERENCES CUSTOMER_TYPE (TYPE_ID),
  STATUS_ID     INTEGER REFERENCES CUSTOMER_STATUS (STATUS_ID),
  AD_GROUP      VARCHAR(120),                        -- one AD group per customer
  USER_COUNT    INTEGER DEFAULT 0,                   -- manual now; AD import later
  NOTES         BLOB SUB_TYPE TEXT,                  -- standing info (not events)
  LOGO          BLOB SUB_TYPE BINARY                 -- small image
);
CREATE UNIQUE INDEX IDX_CUSTOMER_AD_GROUP ON CUSTOMER (AD_GROUP);  -- multiple NULLs allowed
CREATE INDEX IDX_CUSTOMER_NAME ON CUSTOMER (NAME);

/* ---------- Additional contacts (main contact lives in CUSTOMER) ---------- */

CREATE TABLE CONTACT (
  CONTACT_ID  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  WAVE_ID     VARCHAR(100) CHARACTER SET ASCII NOT NULL REFERENCES CUSTOMER (WAVE_ID),
  NAME        VARCHAR(120),
  EMAIL       VARCHAR(200),
  PHONE       VARCHAR(40),
  JOB_TITLE   VARCHAR(60)
);
CREATE INDEX IDX_CONTACT_CUSTOMER ON CONTACT (WAVE_ID);

/* ---------- Customer log (timeline: automatic + manual entries) ---------- */

CREATE TABLE CUSTOMER_LOG (
  LOG_ID        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  WAVE_ID       VARCHAR(100) CHARACTER SET ASCII NOT NULL REFERENCES CUSTOMER (WAVE_ID),
  EVENT_DATE    DATE DEFAULT CURRENT_DATE NOT NULL,            -- when it happened (editable; back-date manual entries)
  LOGGED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,  -- when the row was created
  LOGGED_BY     VARCHAR(63) DEFAULT CURRENT_USER,
  ENTRY_SOURCE  CHAR(1) DEFAULT 'M' NOT NULL CHECK (ENTRY_SOURCE IN ('A', 'M')),  -- A automatic, M manual
  FIELD_NAME    VARCHAR(40),                                   -- null for manual entries
  OLD_VALUE     VARCHAR(200),
  NEW_VALUE     VARCHAR(200),
  SUMMARY       VARCHAR(500) NOT NULL
);
CREATE INDEX IDX_LOG_CUSTOMER ON CUSTOMER_LOG (WAVE_ID, EVENT_DATE);

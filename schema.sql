/* ==========================================================================
   ccCRM - Firebird 5 schema, part 1: tables and seed data (dialect 3)

   Create the database first, with UTF-8 as the default character set, e.g. in isql:

     CREATE DATABASE 'localhost:E:\Data\ccCRM.fdb'
       USER 'SYSDBA' PASSWORD '...' PAGE_SIZE 8192
       DEFAULT CHARACTER SET UTF8;

   Run this file first, then schema-programmability.sql (view, procedure, triggers).
   No COMMIT statements and no domain: DBeaver (auto-commit) commits each DDL
   statement itself, and this runs cleanly there.

   Notes
   - Wave is the master for identity/contact data. Columns marked "Wave-owned"
     are overwritten by the sync; columns marked "Yours" are never touched by it.
   - Customers are never deleted. The sync sets IN_WAVE = FALSE when a customer
     disappears from Wave.
   - Ids use IDENTITY columns (no generators/triggers needed).
   ========================================================================== */

